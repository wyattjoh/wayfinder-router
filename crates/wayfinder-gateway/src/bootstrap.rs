//! Bootstrap helpers for `wayfinder-router init` / `doctor`.
//!
//! Pure scaffolding to get started fast: render a starter `wayfinder-router.toml`
//! from a preset, a matching `.env.example` (env-var *names* only, never a secret),
//! and report whether each model's key resolves from the environment.
//!
//! Wayfinder reads keys from the environment at request time and never stores them
//! (WF-ADR-0004); these helpers only ever name the variables.

use std::collections::{BTreeMap, BTreeSet};
use std::io::Read;
use std::process::{Command, Stdio};
use std::sync::LazyLock;
use std::time::{Duration, Instant};

use crate::GatewayModel;

/// How long to wait on a key-resolution command (WF-DESIGN-0006), generous enough
/// for an interactive vault unlock (e.g. a 1Password biometric prompt).
const KEY_CMD_TIMEOUT: Duration = Duration::from_secs(30);

/// A named starter configuration: the toml to write and the env vars it needs.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Preset {
    pub name: &'static str,
    pub summary: &'static str,
    pub config_toml: &'static str,
    pub env_vars: &'static [&'static str],
}

